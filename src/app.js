import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import routes from './routes/index.js';
import { notFound, errorHandler } from './middleware/errors.js';
const app = express();
const origins = (process.env.CLIENT_ORIGIN || 'http://localhost:8000,http://127.0.0.1:8000').split(',').map(x => x.trim());
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin(origin, cb) { if (!origin || origins.includes(origin)) return cb(null, true); cb(new Error('Origin not allowed by CORS')); }, credentials: true, methods: ['GET','POST','PATCH','PUT','DELETE','OPTIONS'] }));
app.use(express.json({ limit: '1mb' })); app.use(express.urlencoded({ extended: true, limit: '1mb' })); app.use(cookieParser());
if (process.env.NODE_ENV !== 'test') app.use(morgan('tiny'));
app.get('/health', (_req, res) => res.json({ success: true, data: { status: 'ok', service: 'BASMA API', timestamp: new Date().toISOString() } }));
app.use('/api/v1/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-8', legacyHeaders: false }));
app.use('/api/v1', rateLimit({ windowMs: 60 * 1000, limit: 240, standardHeaders: 'draft-8', legacyHeaders: false }), routes);
app.use(notFound); app.use(errorHandler);
export default app;
